"""Step 0: minimal single-OD test network with two corridor families.

Topology (nodes):   O=0, A=1, A1=2, A2=3, B=4, B1=5, B2=6, M=7, X=8, D=9

    O ── A ── A1 ──┐
         └── A2 ──── M ── D          corridor family A (entry link congested)
    O ── B ── B1 ──┤
         └── B2 ──┘                  corridor family B (entry link congested)
    O ────── X ────────── D          bypass (long, uncongested; only priced in
                                     under heavy congestion -> Generate demo)

The two families share the congested exit link M->D, so this is NOT a pure
parallel-link network: link interaction across and within families is real.

Primitive paths (free-flow costs):
    p1 = O-A-A1-M-D   16.0    family A
    p2 = O-A-A2-M-D   16.0    family A
    p3 = O-B-B1-M-D   16.0    family B
    p4 = O-B-B2-M-D   16.05   family B
    p5 = O-X-D        18.0    bypass

Scenarios (the write-up's B = "demand up OR capacity down" is played as its two
sub-cases B1 and B2):
    A  normal demand (q=100)         within-family costs nearly equal ->
                                     coarse atoms suffice, frontier stays small
    B1 incident only (q=100,         family-A heterogeneity spikes -> promote
       cap(A1->M): 70 -> 15)         releases p2; family B stays fully latent:
                                     only the affected branch expands
    B2 incident + demand surge       q=140 on top of the incident: the bypass
                                     becomes competitive and is Generated by
                                     exact pricing; family B's frozen 0.3/0.7
                                     also fails and is released
    C  recovery (q=100, caps back)   costs re-equalise -> merge re-forms the
                                     latent items at the *learned* proportions;
                                     the bypass column is dropped
"""

from atoms import Atom
from network import Network, PathRegistry

O, A, A1, A2, B, B1, B2, M, X, D = range(10)

LINKS = [
    (O, A, 5.00, 60.0),    # 0  family-A entry     (congested)
    (A, A1, 4.00, 80.0),   # 1
    (A, A2, 4.00, 80.0),   # 2
    (A1, M, 3.00, 70.0),   # 3  <- incident link in scenario B
    (A2, M, 3.00, 70.0),   # 4
    (O, B, 6.00, 70.0),    # 5  family-B entry     (congested)
    (B, B1, 3.00, 80.0),   # 6
    (B, B2, 3.05, 80.0),   # 7
    (B1, M, 3.00, 70.0),   # 8
    (B2, M, 3.00, 70.0),   # 9
    (M, D, 4.00, 120.0),   # 10 shared exit        (congested, cross-family)
    (O, X, 9.00, 100.0),   # 11 bypass
    (X, D, 9.00, 100.0),   # 12 bypass
]

ORIGIN, DEST = O, D

SCENARIOS = [
    {"name": "A_normal",    "q": 100.0, "cap_overrides": {}},
    {"name": "B1_incident", "q": 100.0, "cap_overrides": {3: 15.0}},
    {"name": "B2_surge",    "q": 140.0, "cap_overrides": {3: 15.0}},
    {"name": "C_recovery",  "q": 100.0, "cap_overrides": {}},
    # repeat of the incident AFTER the hierarchy has re-merged: shows that a
    # merged latent item re-splits exactly when its reduced-gradient
    # heterogeneity re-crosses the (hysteresis-protected) split threshold
    {"name": "D_reshock",   "q": 100.0, "cap_overrides": {3: 15.0}},
]


def build():
    """Returns (net, registry, path_ids, initial_atoms)."""
    net = Network(10, LINKS)
    reg = PathRegistry(net)
    p1 = reg.add_by_nodes([O, A, A1, M, D], name="p1")
    p2 = reg.add_by_nodes([O, A, A2, M, D], name="p2")
    p3 = reg.add_by_nodes([O, B, B1, M, D], name="p3")
    p4 = reg.add_by_nodes([O, B, B2, M, D], name="p4")
    # Step 1: initial latent items with deliberately non-equilibrium proportions
    h_A = Atom([p1, p2], [0.6, 0.4], name="family_A")
    h_B = Atom([p3, p4], [0.3, 0.7], name="family_B")
    return net, reg, (p1, p2, p3, p4), [h_A, h_B]


def apply_scenario(net, scen):
    net.cap[:] = net.base_cap
    for e, cap in scen["cap_overrides"].items():
        net.cap[e] = cap
    return scen["q"]
